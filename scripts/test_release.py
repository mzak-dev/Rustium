class GitRepoTestCase(unittest.TestCase):
    """A throwaway git repository with a two-crate workspace."""

    def setUp(self) -> None:
        self.tempdir = tempfile.TemporaryDirectory()
        self.root = Path(self.tempdir.name)
        self.repo = Repo(self.root)
        env = {
            "GIT_AUTHOR_NAME": "Test",
            "GIT_AUTHOR_EMAIL": "test@example.com",
            "GIT_COMMITTER_NAME": "Test",
            "GIT_COMMITTER_EMAIL": "test@example.com",
            "GIT_CONFIG_GLOBAL": os.devnull,
            "GIT_CONFIG_NOSYSTEM": "1",
        }
        self.env_patch = mock.patch.dict(os.environ, env)
        self.env_patch.start()
        self.git("init", "--quiet", "--initial-branch=main")
        self.write("Cargo.toml", MANIFEST)
        self.write("Cargo.lock", LOCK)
        self.write("crates/demo-core/Cargo.toml", MEMBER.format(name="demo-core"))
        self.write("crates/demo-app/Cargo.toml", MEMBER.format(name="demo-app"))
        self.commit("chore: initial workspace")

    def tearDown(self) -> None:
        self.env_patch.stop()
        self.tempdir.cleanup()

    def git(self, *args: str) -> str:
        return subprocess.run(["git", *args], cwd=self.root, check=True, capture_output=True, text=True).stdout.strip()

    def write(self, path: str, text: str) -> None:
        file = self.root / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(text, encoding="utf-8")

    def commit(self, message: str, path: str | None = None) -> str:
        if path is not None:
            self.write(path, message)
        self.git("add", "--all")
        self.git("commit", "--quiet", "--allow-empty", "--message", message)
        return self.git("rev-parse", "HEAD")

    def release_branch(self) -> tuple[str, str]:
        """Prepares a release commit on `release/next`; returns (base, head)."""
        base = self.git("rev-parse", "HEAD")
        self.git("switch", "--quiet", "-c", "release/next")
        version = release.prepare(self.repo, None, DATE, URL)
        head = self.commit(f"chore(release): {version.tag}")
        self.git("switch", "--quiet", "main")
        return base, head


class PlanTests(GitRepoTestCase):
    def test_no_releasable_commits_means_nothing_to_do(self) -> None:
        self.commit("docs: readme", "README.md")
        self.assertEqual(release.plan(self.repo, "HEAD", force=False)["mode"], "none")

    def test_first_release_is_proposed_from_the_whole_history(self) -> None:
        self.commit("feat(app): first tool", "a.rs")
        outputs = release.plan(self.repo, "HEAD", force=False)
        self.assertEqual((outputs["mode"], outputs["next-version"]), ("pr", "0.2.0"))

    def test_proposes_the_bump_since_the_last_tag(self) -> None:
        self.commit("feat: before the release", "a.rs")
        self.git("tag", "v0.1.0")
        self.commit("fix(render): after the release", "b.rs")
        outputs = release.plan(self.repo, "HEAD", force=False)
        self.assertEqual((outputs["mode"], outputs["next-version"]), ("pr", "0.1.1"))

    def test_merged_first_bump_is_released(self) -> None:
        self.commit("feat: tool", "a.rs")
        self.release_branch()
        self.git("merge", "--quiet", "--ff-only", "release/next")
        outputs = release.plan(self.repo, "HEAD", force=False)
        self.assertEqual((outputs["mode"], outputs["tag"], outputs["previous-tag"]), ("release", "v0.2.0", ""))

    def test_first_release_is_still_due_after_later_pushes(self) -> None:
        self.commit("feat: tool", "a.rs")
        self.release_branch()
        self.git("merge", "--quiet", "--ff-only", "release/next")
        self.commit("fix: landed before the release run", "b.rs")
        self.assertEqual(release.plan(self.repo, "HEAD", force=False)["mode"], "release")

    def test_untagged_version_after_a_failed_release_is_retried(self) -> None:
        self.git("tag", "v0.1.0")
        self.write("Cargo.toml", MANIFEST.replace("0.1.0", "0.1.1"))
        self.commit("chore(release): v0.1.1")
        self.commit("docs: later push", "README.md")
        outputs = release.plan(self.repo, "HEAD", force=False)
        self.assertEqual((outputs["mode"], outputs["tag"], outputs["previous-tag"]), ("release", "v0.1.1", "v0.1.0"))

    def test_released_version_goes_back_to_proposing(self) -> None:
        self.write("Cargo.toml", MANIFEST.replace("0.1.0", "0.2.0"))
        self.commit("chore(release): v0.2.0")
        self.git("tag", "v0.2.0")
        self.assertEqual(release.plan(self.repo, "HEAD", force=False)["mode"], "none")
        self.commit("perf(core): faster mesher", "a.rs")
        outputs = release.plan(self.repo, "HEAD", force=False)
        self.assertEqual((outputs["mode"], outputs["next-version"]), ("pr", "0.2.1"))

    def test_untagged_starting_version_needs_force(self) -> None:
        self.commit("fix: x", "a.rs")
        self.assertEqual(release.plan(self.repo, "HEAD", force=False)["mode"], "pr")
        self.assertEqual(release.plan(self.repo, "HEAD", force=True)["mode"], "release")

    def test_forcing_an_existing_tag_is_an_error(self) -> None:
        self.git("tag", "v0.1.0")
        with self.assertRaises(ReleaseError):
            release.plan(self.repo, "HEAD", force=True)

    def test_version_behind_the_latest_tag_is_an_error(self) -> None:
        self.git("tag", "v0.5.0")
        self.commit("fix: x", "a.rs")
        with self.assertRaises(ReleaseError):
            release.plan(self.repo, "HEAD", force=False)


class PrepareAndVerifyTests(GitRepoTestCase):
    def setUp(self) -> None:
        super().setUp()
        self.git("tag", "v0.1.0")
        self.commit("feat(app): tool wheel (#7)", "a.rs")
        self.commit("fix(render)!: drop the old shader cache", "b.rs")
        self.commit("docs: readme", "README.md")

    def test_prepare_writes_manifest_lock_and_changelog(self) -> None:
        version = release.prepare(self.repo, None, DATE, URL)
        self.assertEqual(version, Version(0, 2, 0))
        self.assertEqual(self.repo.workspace_version(None), version)
        lock = (self.root / "Cargo.lock").read_text()
        self.assertIn('name = "demo-core"\nversion = "0.2.0"', lock)
        self.assertIn('name = "serde"\nversion = "0.1.0"', lock)
        changelog = (self.root / "CHANGELOG.md").read_text()
        self.assertIn("## [0.2.0](https://github.com/example/demo/compare/v0.1.0...v0.2.0) - 2026-11-12", changelog)
        self.assertIn("drop the old shader cache", changelog)
        self.assertEqual(release.release_notes(self.repo, version, URL), release.find_section(changelog, version))

    def test_prepare_refuses_when_nothing_is_releasable(self) -> None:
        self.git("tag", "v0.1.1")
        with self.assertRaises(ReleaseError):
            release.prepare(self.repo, None, DATE, URL)

    def test_genuine_release_pr_verifies(self) -> None:
        base, head = self.release_branch()
        self.assertEqual(release.verify_pr(self.repo, base, head), Version(0, 2, 0))

    def test_verification_uses_the_merge_base_when_main_moved_on(self) -> None:
        base, head = self.release_branch()
        new_base = self.commit("feat: landed after the PR was made", "c.rs")
        self.assertEqual(release.verify_pr(self.repo, new_base, head), Version(0, 2, 0))

    def test_rejects_a_wrong_version(self) -> None:
        base = self.git("rev-parse", "HEAD")
        self.git("switch", "--quiet", "-c", "release/next")
        release.prepare(self.repo, Version(1, 0, 0), DATE, URL)
        head = self.commit("chore(release): v1.0.0")
        with self.assertRaisesRegex(ReleaseError, "call for 0.2.0"):
            release.verify_pr(self.repo, base, head)

    def test_rejects_other_files(self) -> None:
        base, _ = self.release_branch()
        self.git("switch", "--quiet", "release/next")
        self.write("build.rs", "fn main() {}")
        self.git("add", "--all")
        self.git("commit", "--quiet", "--amend", "--no-edit")
        head = self.git("rev-parse", "HEAD")
        with self.assertRaisesRegex(ReleaseError, "build.rs"):
            release.verify_pr(self.repo, base, head)

    def test_rejects_a_dependency_change_hidden_in_the_manifest(self) -> None:
        base, _ = self.release_branch()
        self.git("switch", "--quiet", "release/next")
        manifest = (self.root / "Cargo.toml").read_text().replace('serde = "1"', 'serde = { git = "https://evil" }')
        self.write("Cargo.toml", manifest)
        self.git("commit", "--quiet", "--all", "--amend", "--no-edit")
        head = self.git("rev-parse", "HEAD")
        with self.assertRaisesRegex(ReleaseError, "Cargo.toml changes more"):
            release.verify_pr(self.repo, base, head)

    def test_rejects_a_lockfile_change_beyond_workspace_versions(self) -> None:
        base, _ = self.release_branch()
        self.git("switch", "--quiet", "release/next")
        lock = (self.root / "Cargo.lock").read_text().replace('checksum = "abc"', 'checksum = "evil"')
        self.write("Cargo.lock", lock)
        self.git("commit", "--quiet", "--all", "--amend", "--no-edit")
        head = self.git("rev-parse", "HEAD")
        with self.assertRaisesRegex(ReleaseError, "Cargo.lock changes more"):
            release.verify_pr(self.repo, base, head)

    def test_rejects_more_than_one_commit(self) -> None:
        base, _ = self.release_branch()
        self.git("switch", "--quiet", "release/next")
        head = self.commit("chore: sneak in")
        with self.assertRaisesRegex(ReleaseError, "exactly one commit"):
            release.verify_pr(self.repo, base, head)

    def test_rejects_a_bump_when_nothing_is_releasable(self) -> None:
        self.git("tag", "v0.1.1")
        base = self.git("rev-parse", "HEAD")
        self.git("switch", "--quiet", "-c", "release/next")
        release.prepare(self.repo, Version(0, 1, 2), DATE, URL)
        head = self.commit("chore(release): v0.1.2")
        with self.assertRaisesRegex(ReleaseError, "nothing to bump"):
            release.verify_pr(self.repo, base, head)


